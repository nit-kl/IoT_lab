-- 模擬の工場 DB。長年使われた基幹システムを想定し、略語の表名・列名、コード値、
-- システムごとに異なる設備 ID を意図的に残している（方針書 4 章）。
-- 外部キーは業務システム内で完結する部分だけに付け、PLC 連携・保全システム連携の列には付けない。
-- 全表の共通列: UPD_TS は差分抽出の基準、DEL_FLG は論理削除（1 で削除）。

-- ---------- マスタ ----------
CREATE TABLE M_KOJO (
  KOJO_CD VARCHAR2(8 CHAR) PRIMARY KEY,
  KOJO_NM VARCHAR2(60 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_AREA (
  AREA_CD VARCHAR2(8 CHAR) PRIMARY KEY,
  KOJO_CD VARCHAR2(8 CHAR) NOT NULL REFERENCES M_KOJO (KOJO_CD),
  AREA_NM VARCHAR2(60 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_LINE (
  LINE_CD VARCHAR2(8 CHAR) PRIMARY KEY,
  AREA_CD VARCHAR2(8 CHAR) NOT NULL REFERENCES M_AREA (AREA_CD),
  LINE_NM VARCHAR2(60 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_KATASHIKI (
  KATA_CD VARCHAR2(16 CHAR) PRIMARY KEY,
  MAKER_NM VARCHAR2(60 CHAR) NOT NULL,
  KATA_NM VARCHAR2(60 CHAR) NOT NULL,
  KIKI_KBN VARCHAR2(8 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_KIKAI (
  KIKAI_CD VARCHAR2(16 CHAR) PRIMARY KEY,
  LINE_CD VARCHAR2(8 CHAR) NOT NULL REFERENCES M_LINE (LINE_CD),
  KATA_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_KATASHIKI (KATA_CD),
  OYA_KIKAI_CD VARCHAR2(16 CHAR) REFERENCES M_KIKAI (KIKAI_CD),
  KIKAI_NM VARCHAR2(60 CHAR) NOT NULL,
  SECCHI_DT DATE NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_KIKAI_ALIAS (
  SYS_KBN VARCHAR2(8 CHAR) NOT NULL,
  GAIBU_CD VARCHAR2(16 CHAR) NOT NULL,
  KIKAI_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_KIKAI (KIKAI_CD),
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL,
  PRIMARY KEY (SYS_KBN, GAIBU_CD)
);
CREATE TABLE M_BUHIN (
  BUHIN_CD VARCHAR2(16 CHAR) PRIMARY KEY,
  BUHIN_NM VARCHAR2(60 CHAR) NOT NULL,
  BUHIN_KBN VARCHAR2(8 CHAR) NOT NULL,
  TANI VARCHAR2(8 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_BUHIN_KOSEI (
  OYA_BUHIN_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_BUHIN (BUHIN_CD),
  KO_BUHIN_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_BUHIN (BUHIN_CD),
  SURYO NUMBER(8, 2) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL,
  PRIMARY KEY (OYA_BUHIN_CD, KO_BUHIN_CD)
);
CREATE TABLE M_SHIIRESAKI (
  SHIIRE_CD VARCHAR2(8 CHAR) PRIMARY KEY,
  SHIIRE_NM VARCHAR2(60 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_HINMOKU (
  HIN_CD VARCHAR2(16 CHAR) PRIMARY KEY,
  HIN_NM VARCHAR2(60 CHAR) NOT NULL,
  HYOJUN_CT_SEC NUMBER(8, 1) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_SHAIN (
  SHAIN_NO VARCHAR2(8 CHAR) PRIMARY KEY,
  SHAIN_NM VARCHAR2(60 CHAR) NOT NULL,
  SHOZOKU_NM VARCHAR2(60 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_YAKUWARI (
  YAKU_CD VARCHAR2(8 CHAR) PRIMARY KEY,
  YAKU_NM VARCHAR2(60 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_TANTO_HANI (
  TANTO_ID NUMBER(10) PRIMARY KEY,
  SHAIN_NO VARCHAR2(8 CHAR) NOT NULL REFERENCES M_SHAIN (SHAIN_NO),
  YAKU_CD VARCHAR2(8 CHAR) NOT NULL REFERENCES M_YAKUWARI (YAKU_CD),
  HANI_KBN VARCHAR2(8 CHAR) NOT NULL,
  HANI_CD VARCHAR2(16 CHAR) NOT NULL,
  KAISHI_DT DATE NOT NULL,
  SHURYO_DT DATE,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE M_CODE (
  CD_KBN VARCHAR2(16 CHAR) NOT NULL,
  CD VARCHAR2(16 CHAR) NOT NULL,
  CD_NM VARCHAR2(60 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL,
  PRIMARY KEY (CD_KBN, CD)
);
CREATE TABLE M_KPI_MOKUHYO (
  LINE_CD VARCHAR2(8 CHAR) NOT NULL REFERENCES M_LINE (LINE_CD),
  KPI_CD VARCHAR2(8 CHAR) NOT NULL,
  MOKUHYO_VAL NUMBER(10, 3) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL,
  PRIMARY KEY (LINE_CD, KPI_CD)
);

-- ---------- トランザクション ----------
CREATE TABLE T_TOBAN (
  TOBAN_ID NUMBER(10) PRIMARY KEY,
  SHAIN_NO VARCHAR2(8 CHAR) NOT NULL REFERENCES M_SHAIN (SHAIN_NO),
  AREA_CD VARCHAR2(8 CHAR) NOT NULL REFERENCES M_AREA (AREA_CD),
  KAISHI_TS TIMESTAMP NOT NULL,
  SHURYO_TS TIMESTAMP NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE T_LOT (
  LOT_NO VARCHAR2(16 CHAR) PRIMARY KEY,
  BUHIN_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_BUHIN (BUHIN_CD),
  SHIIRE_CD VARCHAR2(8 CHAR) NOT NULL REFERENCES M_SHIIRESAKI (SHIIRE_CD),
  UKEIRE_DT DATE NOT NULL,
  SURYO NUMBER(10, 2) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE T_BUHIN_TORITSUKE (
  TORI_ID NUMBER(10) PRIMARY KEY,
  KIKAI_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_KIKAI (KIKAI_CD),
  BUHIN_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_BUHIN (BUHIN_CD),
  LOT_NO VARCHAR2(16 CHAR) NOT NULL REFERENCES T_LOT (LOT_NO),
  TORITSUKE_TS TIMESTAMP NOT NULL,
  TORIHAZUSHI_TS TIMESTAMP,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE T_SEIZO_SHIJI (
  SHIJI_NO VARCHAR2(20 CHAR) PRIMARY KEY,
  HIN_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_HINMOKU (HIN_CD),
  LINE_CD VARCHAR2(8 CHAR) NOT NULL REFERENCES M_LINE (LINE_CD),
  SHIJI_SURYO NUMBER(10) NOT NULL,
  KAISHI_YOTEI_TS TIMESTAMP NOT NULL,
  NOKI_DT DATE NOT NULL,
  JOTAI_KBN VARCHAR2(8 CHAR) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE T_SHIJI_LOT (
  SHIJI_NO VARCHAR2(20 CHAR) NOT NULL REFERENCES T_SEIZO_SHIJI (SHIJI_NO),
  LOT_NO VARCHAR2(16 CHAR) NOT NULL REFERENCES T_LOT (LOT_NO),
  SHIYO_SURYO NUMBER(10, 2) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL,
  PRIMARY KEY (SHIJI_NO, LOT_NO)
);
CREATE TABLE T_SEISAN_JISSEKI (
  JISSEKI_ID NUMBER(12) PRIMARY KEY,
  SHIJI_NO VARCHAR2(20 CHAR) NOT NULL REFERENCES T_SEIZO_SHIJI (SHIJI_NO),
  KIKAI_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_KIKAI (KIKAI_CD),
  KAISHI_TS TIMESTAMP NOT NULL,
  SHURYO_TS TIMESTAMP NOT NULL,
  OK_SU NUMBER(10) NOT NULL,
  NG_SU NUMBER(10) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE T_HINSHITSU_KENSA (
  KENSA_ID NUMBER(12) PRIMARY KEY,
  SHIJI_NO VARCHAR2(20 CHAR) NOT NULL REFERENCES T_SEIZO_SHIJI (SHIJI_NO),
  KENSA_TS TIMESTAMP NOT NULL,
  KENSA_SU NUMBER(10) NOT NULL,
  NG_SU NUMBER(10),
  FURYO_CD VARCHAR2(16 CHAR),
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
-- PLC 連携の表。SRC_EQP_ID は PLC 側の設備 ID（M_KIKAI_ALIAS で読み替える）
CREATE TABLE T_EQP_ALM (
  ALM_ID NUMBER(12) PRIMARY KEY,
  SRC_EQP_ID VARCHAR2(16 CHAR) NOT NULL,
  ALM_CD VARCHAR2(8 CHAR) NOT NULL,
  ALM_LV NUMBER(1) NOT NULL,
  HASSEI_TS TIMESTAMP NOT NULL,
  FUKKI_TS TIMESTAMP,
  MSG VARCHAR2(200 CHAR),
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE T_TEISHI_KIROKU (
  TEISHI_ID NUMBER(12) PRIMARY KEY,
  KIKAI_CD VARCHAR2(16 CHAR) NOT NULL REFERENCES M_KIKAI (KIKAI_CD),
  RIYU_CD VARCHAR2(8 CHAR) NOT NULL,
  KAISHI_TS TIMESTAMP NOT NULL,
  SHURYO_TS TIMESTAMP,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
-- 保全システム連携の表。GAIBU_KIKAI_CD は保全システム側の設備 ID
CREATE TABLE T_HOZEN (
  HOZEN_ID NUMBER(12) PRIMARY KEY,
  GAIBU_KIKAI_CD VARCHAR2(16 CHAR) NOT NULL,
  ALM_ID NUMBER(12) REFERENCES T_EQP_ALM (ALM_ID),
  SHAIN_NO VARCHAR2(8 CHAR) NOT NULL REFERENCES M_SHAIN (SHAIN_NO),
  CHAKUSHU_TS TIMESTAMP NOT NULL,
  KANRYO_TS TIMESTAMP,
  SHOCHI_MEMO VARCHAR2(400 CHAR),
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL
);
CREATE TABLE T_DENRYOKU (
  LINE_CD VARCHAR2(8 CHAR) NOT NULL REFERENCES M_LINE (LINE_CD),
  KEISOKU_TS TIMESTAMP NOT NULL,
  KWH NUMBER(10, 2) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL,
  PRIMARY KEY (LINE_CD, KEISOKU_TS)
);
-- 高頻度のセンサー値。S3 へは送るがグラフには入れない（方針書 4 章）
CREATE TABLE T_SENSOR_DATA (
  SRC_EQP_ID VARCHAR2(16 CHAR) NOT NULL,
  METRIC_CD VARCHAR2(8 CHAR) NOT NULL,
  KEISOKU_TS TIMESTAMP NOT NULL,
  VAL NUMBER(12, 3) NOT NULL,
  UPD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DEL_FLG CHAR(1) DEFAULT '0' NOT NULL,
  PRIMARY KEY (SRC_EQP_ID, METRIC_CD, KEISOKU_TS)
);

-- ---------- 差分抽出用の索引 ----------
CREATE INDEX IX_TOBAN_UPD ON T_TOBAN (UPD_TS);
CREATE INDEX IX_LOT_UPD ON T_LOT (UPD_TS);
CREATE INDEX IX_TORI_UPD ON T_BUHIN_TORITSUKE (UPD_TS);
CREATE INDEX IX_SHIJI_UPD ON T_SEIZO_SHIJI (UPD_TS);
CREATE INDEX IX_SLOT_UPD ON T_SHIJI_LOT (UPD_TS);
CREATE INDEX IX_JISSEKI_UPD ON T_SEISAN_JISSEKI (UPD_TS);
CREATE INDEX IX_KENSA_UPD ON T_HINSHITSU_KENSA (UPD_TS);
CREATE INDEX IX_ALM_UPD ON T_EQP_ALM (UPD_TS);
CREATE INDEX IX_TEISHI_UPD ON T_TEISHI_KIROKU (UPD_TS);
CREATE INDEX IX_HOZEN_UPD ON T_HOZEN (UPD_TS);
CREATE INDEX IX_DEN_UPD ON T_DENRYOKU (UPD_TS);
CREATE INDEX IX_SENSOR_UPD ON T_SENSOR_DATA (UPD_TS);
